import {Router} from "express";
import {verifyToken} from "../middlewares/jwt.middleware.js";
import {verifyProjectAccess} from "../middlewares/project.middleware.js";
import {verifyApiKey} from "../middlewares/apiKey.middleware.js";
import {requirePermission} from "../middlewares/permission.middleware.js";
import {catalog,listTests,getTest,startTest,finishTest,takeCommands,takeCommandsBatch,confirmCommand,confirmCommandsBatch,createActuator,calibrateSensor,completeSensorRepair} from "../controllers/manual-control.controller.js";

const router=Router();
router.get("/iot/comandos",verifyApiKey,takeCommandsBatch);
router.post("/iot/comandos/confirmaciones",verifyApiKey,confirmCommandsBatch);
router.get("/iot/nodos/:nodeId/comandos",verifyApiKey,takeCommands);
router.post("/iot/comandos/:id/confirmar",verifyApiKey,confirmCommand);
router.get("/catalogo",verifyToken,verifyProjectAccess,requirePermission("pruebas_unitarias.view","gestion_valvulas.view"),catalog);
router.get("/pruebas",verifyToken,verifyProjectAccess,requirePermission("pruebas_unitarias.view","gestion_valvulas.view"),listTests);
router.get("/pruebas/:id",verifyToken,verifyProjectAccess,requirePermission("pruebas_unitarias.view","gestion_valvulas.view"),getTest);
router.post("/pruebas",verifyToken,verifyProjectAccess,requirePermission("pruebas_unitarias.view","gestion_valvulas.view"),startTest);
router.post("/actuadores",verifyToken,verifyProjectAccess,requirePermission("gestion_valvulas.view"),createActuator);
router.post("/sensores/:sensorId/calibracion",verifyToken,verifyProjectAccess,requirePermission("pruebas_unitarias.view"),calibrateSensor);
router.patch("/sensores/:sensorId/reparacion-completada",verifyToken,verifyProjectAccess,requirePermission("pruebas_unitarias.view"),completeSensorRepair);
router.patch("/pruebas/:id/finalizar",verifyToken,verifyProjectAccess,requirePermission("pruebas_unitarias.view","gestion_valvulas.view"),finishTest);
export default router;
